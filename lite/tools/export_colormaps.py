"""Export the full app's colormaps as Rust lookup tables.

The Graph Properties colormaps are built exactly as ``MainWindow._plot_cmap``
builds them, and both tables the hardware canvas uses are taken from its own
functions (``src/ui/widgets/accelerated_plot_widget.py``):

* ``lut``: pyqtgraph's 256-entry table (``_mpl_cmap_to_lookup``), used for
  images without NaN;
* ``exact``: matplotlib's own colours (``_rgba_lut_for_cmap``), used for
  images with gaps or NaN.

usage: python lite/tools/export_colormaps.py
Writes lite/crates/callisto-core/src/radio/colormap_tables.rs.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

import matplotlib.colors as mcolors  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib import colormaps  # noqa: E402

from src.backend.radio.frequency_axis import transparent_bad_cmap  # noqa: E402
from src.ui.widgets.accelerated_plot_widget import _mpl_cmap_to_lookup, _rgba_lut_for_cmap  # noqa: E402

# MainWindow.cmap_combo, in order.
NAMES = ["Custom", "viridis", "plasma", "inferno", "magma", "cividis", "turbo", "RdYlBu", "jet", "cubehelix", "bone_r"]


# Not in the list: the Combine FITS Files preview's colormap
# (CombineFitsDialog._render_preview).
EXTRA = ["combined_preview"]


def build(name: str):
    if name == "combined_preview":
        cmap = mcolors.LinearSegmentedColormap.from_list(
            "combined_preview", [(0.0, "#123a8c"), (0.5, "#d83b34"), (1.0, "#ffd447")]
        )
    elif name == "Custom":
        cmap = mcolors.LinearSegmentedColormap.from_list("custom_RdYlBu", [(0.0, "blue"), (0.5, "red"), (1.0, "yellow")])
    else:
        cmap = colormaps.get_cmap(name)
    return transparent_bad_cmap(cmap)


def table(rows) -> str:
    rows = np.asarray(rows, dtype=np.uint8)
    if rows.shape[1] == 3:
        # pyqtgraph drops the alpha column when every colour is opaque.
        rows = np.hstack([rows, np.full((rows.shape[0], 1), 255, dtype=np.uint8)])
    return "&[" + ", ".join(f"[{r[0]}, {r[1]}, {r[2]}, {r[3]}]" for r in rows) + "]"


def main() -> int:
    out = [
        "//! Generated by `lite/tools/export_colormaps.py` from the full app's own",
        "//! colormap code; do not edit by hand.",
        "",
        "/// `(name, pyqtgraph lookup table, matplotlib table)`.",
        "pub type ColormapEntry = (&'static str, &'static [[u8; 4]], &'static [[u8; 4]]);",
        "",
        "pub const COLORMAPS: &[ColormapEntry] = &[",
    ]
    for name in NAMES + EXTRA:
        cmap = build(name)
        _color_map, lut = _mpl_cmap_to_lookup(cmap)
        exact = _rgba_lut_for_cmap(cmap)
        out.append(f'    ("{name}", {table(lut)}, {table(exact)}),')
        print(f"{name}: lut {np.asarray(lut).shape}, exact {np.asarray(exact).shape}")
    out.append("];")
    path = REPO / "lite" / "crates" / "callisto-core" / "src" / "radio" / "colormap_tables.rs"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
